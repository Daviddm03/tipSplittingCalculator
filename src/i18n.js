    function t(key, params = {}) {
        const resolvedKey = Number(params.count) === 1 && Object.hasOwn(translations[language], key + '.one')
            ? key + '.one' : key;
        const value = translations[language][resolvedKey] ?? translations.en[resolvedKey] ?? key;
        return value.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
    }
    function locale() { return language === 'pt' ? 'pt-PT' : 'en-IE'; }
    function translate(root = global.document) {
        if (!root) return;
        const nodes = [...(root.querySelectorAll?.('[data-i18n], [data-i18n-placeholder], [data-i18n-aria-label], [data-i18n-title], [data-i18n-alt]') || [])];
        if (root.matches?.('[data-i18n], [data-i18n-placeholder], [data-i18n-aria-label], [data-i18n-title], [data-i18n-alt]')) nodes.unshift(root);
        nodes.forEach(node => {
            if (node.dataset.i18n) node.textContent = t(node.dataset.i18n);
            ['placeholder', 'aria-label', 'title', 'alt'].forEach(attribute => {
                const key = node.getAttribute('data-i18n-' + attribute);
                if (key) node.setAttribute(attribute, t(key));
            });
        });
    }
    function setLanguage(value) {
        language = value === 'pt' ? 'pt' : 'en';
        let persisted = true, failure = null;
        try { global.localStorage.setItem(storageKey, language); } catch (error) { persisted = false; failure = error; }
        if (global.document) global.document.documentElement.lang = language;
        translate();
        const result = { language, persisted, error: failure };
        global.dispatchEvent?.(new global.CustomEvent('tipsplit:languagechange', { detail: result }));
        return result;
    }
